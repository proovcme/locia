    public static function sectionsFor(string $type): array
    {
        return $type === 'rd21' ? self::rdSets() : self::pdSections();
    }

    public static function taskTemplates(string $type): array
    {
        $sections = self::sectionsFor($type);
        $verb = $type === 'rd21' ? 'Подготовить комплект РД' : 'Подготовить раздел ПД';

        return array_map(static fn (array $section): array => [
            'title' => $verb . ' ' . $section['code'] . ' - ' . $section['title'],
            'discipline' => $section['code'],
            'volume' => $section['code'],
            'section' => $section['code'],
            'what' => $verb . ' ' . $section['code'] . ' и передать на проверку.',
            'why' => $type === 'rd21'
                ? 'Шаблон сформирован по маркам основных комплектов рабочей документации.'
                : 'Шаблон сформирован по типовому составу проектной документации.',
        ], $sections);
    }
